export default function I18nProvider({ children }: { children: React.ReactNode }) {
  const [isReady, setIsReady] = useState(false);
  const i18nInstance = useRef<typeof i18n | null>(null);

  useEffect(() => {
    if (!i18nInstance.current && typeof window !== 'undefined') {
      const instance = i18n.createInstance();
      instance
        .use(initReactI18next)
        .init({
          resources,
          lng: 'en',
          fallbackLng: 'en',
          interpolation: {
            escapeValue: false,
          },
        })
        .then(() => {
          i18nInstance.current = instance;
          setIsReady(true);
        });
    }
  }, []);

  if (!isReady || !i18nInstance.current) {
    return <div className="min-h-screen bg-background" />;
  }

  return <I18nextProvider i18n={i18nInstance.current}>{children}</I18nextProvider>;
}